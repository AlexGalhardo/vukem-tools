function apiPages(): Map<string, string> {
	const pages = new Map<string, string>();
	const byFamily = new Map<string, Route[]>();
	for (const r of routes) {
		const f = familyOf(r.path).slug;
		byFamily.set(f, [...(byFamily.get(f) ?? []), r]);
	}
	const order = (r: Route): string => r.path + METHOD_RANK[r.method];
	for (const f of families) {
		const list = (byFamily.get(f.slug) ?? []).sort((a, b) => order(a).localeCompare(order(b)));
		const parts: string[] = [`${f.blurb} Every example reads the server from \`VUKEM_TOOLS_URL\` and the key from \`VUKEM_TOOLS_API_KEY\`; see [the overview](/docs/api/overview) for how to set them.`, ""];
		if (f.slug === "conversions") parts.push(conversionObject(), "");
		for (const r of list) parts.push(routeSection(r));
		if (f.slug === "conversions") parts.push(eventsSection);
		pages.set(`api/${f.slug}`, pageText(f.title, f.blurb, parts.join("\n")));
	}

	// the index: one row per route, linking to its section
	const all: { method: string; path: string; summary: string; slug: string; ability: string }[] = [
		...routes.map((r) => ({
			method: r.method,
			path: r.path,
			summary: r.op.summary ?? "",
			slug: familyOf(r.path).slug,
			ability: !r.op.security ? "public" : (toolOfPath(r.path) && r.method === "POST" && ABILITY[toolOfPath(r.path) as string]) || "any key",
		})),
		{ method: EVENTS_ROUTE.method, path: EVENTS_ROUTE.path, summary: "Follow a conversion as it runs", slug: "conversions", ability: "any key" },
	];
	const sections = families.map((f) => {
		const rows = all
			.filter((x) => x.slug === f.slug)
			.sort((a, b) => (a.path + METHOD_RANK[a.method]).localeCompare(b.path + METHOD_RANK[b.method]))
			.map((x) => {
				const anchor = new GithubSlugger().slug(`${x.method} ${x.path}`);
				return [`[${code(`${x.method} ${x.path}`)}](/docs/api/${x.slug}#${anchor})`, esc(cap(x.summary)), x.ability === "public" || x.ability === "any key" ? x.ability : code(x.ability)];
			});
		return `## ${f.title}\n\n${f.blurb}\n\n${table(["Route", "What it does", "Needs"], rows)}`;
	});
	pages.set(
		"api/endpoints",
		pageText(
			"Endpoints",
			`All ${all.length} routes under /api/v1, grouped by family.`,
			`The API has ${all.length} routes under \`/api/v1\`. This table is the index; each row links to the section that has the parameters, the body, a \`curl\` example and the responses. "Needs" is the ability a key must carry: \`public\` means no key, \`any key\` means any valid key.\n\nTwo more routes sit outside \`/api/v1\` because they do not speak JSON: the resumable upload at \`/uploads/tus/\` and the signed download at \`/files/{id}\`. Both are in [Convert a file](/docs/api/workflow).\n\n${sections.join("\n\n")}`,
		),
	);
	return pages;
}


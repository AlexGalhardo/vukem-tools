/** The options of the matching API example when it has any, else placeholders for the required fields. */
function exampleOptions(t: Tool): Record<string, unknown> | undefined {
	if (!t.options) return undefined;
	const op = routes.find((r) => r.op.operationId === t.operation);
	const body = exampleOf(op?.op.requestBody?.content?.["application/json"]?.schema) as { options?: Record<string, unknown> } | undefined;
	if (body?.options && Object.keys(body.options).length) return body.options;
	const out: Record<string, unknown> = {};
	for (const k of t.options.required ?? []) {
		const p = resolve(t.options.properties?.[k]);
		out[k] = k === "url" ? "https://example.com/video" : exampleOf(p, 1);
	}
	return Object.keys(out).length || t.options_required ? out : undefined;
}

/** The tools whose `output` is a directory, and the name of one file such a call may write there. */
const DIRECTORY_OUTPUT: Record<string, string> = {
	"pdf-split": "part-1.pdf",
	"pdf-to-image": "page-1.png",
	"archive-extract": "file.txt",
	"sprite-split": "frame-1.png",
};

function extOf(t: Tool, options: Record<string, unknown> | undefined): { input: string; output: string } {
	const n = t.name;
	const format = typeof options?.format === "string" ? options.format : typeof options?.target === "string" ? options.target : undefined;
	const input = /^(pdf-|image-to-pdf)/.test(n)
		? "pdf"
		: n === "images-to-pdf" || n.startsWith("image-") || n.startsWith("sprite-") || n === "pixels-to-svg"
			? "png"
			: n === "word-to-pdf"
				? "docx"
				: n === "powerpoint-to-pdf"
					? "pptx"
					: n === "excel-to-pdf"
						? "xlsx"
						: n.startsWith("audio-")
							? "mp3"
							: n.startsWith("video-")
								? "mp4"
								: n === "archive-extract"
									? "zip"
									: "txt";
	const output = n.endsWith("-to-pdf") || n.startsWith("pdf-") ? "pdf" : n === "pixels-to-svg" ? "svg" : n === "video-to-gif" ? "gif" : n === "archive-create" ? "zip" : (format ?? input);
	return { input, output: n === "pdf-to-text" ? "txt" : n === "pdf-compare" ? "txt" : output };
}

function typeOfSchema(s: Schema): string {
	const t = Array.isArray(s.type) ? s.type.filter((x) => x !== "null").join(" or ") : (s.type ?? "object");
	return t === "array" ? `array of ${s.items ? typeOfSchema(resolve(s.items)) : "values"}` : t;
}

type OptionRow = { path: string; type: string; required: boolean; text: string };

/** Flattens an object schema into rows with dotted paths, down to `depth` levels. */
function optionRows(schema: Schema | undefined, prefix: string, depth = 3): OptionRow[] {
	const s = resolve(schema);
	const rows: OptionRow[] = [];
	for (const [name, raw] of Object.entries(s.properties ?? {})) {
		const p = resolve(raw);
		rows.push({ path: prefix + name, type: typeOfSchema(p), required: (s.required ?? []).includes(name), text: describe(raw) });
		if (depth > 1 && p.properties) rows.push(...optionRows(p, `${prefix}${name}.`, depth - 1));
		else if (depth > 1 && p.type === "array" && p.items && resolve(p.items).properties) {
			rows.push(...optionRows(resolve(p.items), `${prefix}${name}[].`, depth - 1));
		}
	}
	return rows;
}


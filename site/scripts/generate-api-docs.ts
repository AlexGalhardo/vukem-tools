function toolOfPath(p: string): string | undefined {
	return /^\/api\/v1\/tools\/([a-z-]+)(\/.*)?$/.exec(p)?.[1];
}

function abilityOf(r: Route): string {
	if (!r.op.security) return "None. The route is public.";
	const tool = toolOfPath(r.path);
	if (tool && r.method === "POST" && ABILITY[tool]) return `${code(ABILITY[tool])}`;
	return "Any valid key. No ability is needed.";
}

const pathVars: Record<string, string> = { id: "$CONVERSION_ID", token: "$KEY_ID" };

function curlFor(r: Route): string {
	const url = BASE + r.path.replace(/\{(\w+)\}/g, (_m, n: string) => pathVars[n] ?? `$${n.toUpperCase()}`);
	const parts = [`curl -sS${r.method === "GET" ? "" : ` -X ${r.method}`} "${url}"`];
	if (r.op.security) parts.push(`-H "Authorization: Bearer ${KEY}"`);
	const body = r.op.requestBody?.content?.["application/json"]?.schema;
	if (body) {
		const example = resolve(body).examples?.[0];
		parts.push(`-H "Content-Type: application/json"`);
		parts.push(`-d '${JSON.stringify(example ?? {}, null, 2)}'`);
	}
	return parts.join(" \\\n  ");
}

function responseSection(r: Route): string {
	const rows: string[][] = [];
	let example: unknown;
	let exampleName: string | undefined;
	for (const [status, res] of Object.entries(r.op.responses ?? {})) {
		let meaning = res.description ?? "";
		let body = "";
		if (res.$ref === "#/components/responses/Problem") {
			meaning = "An error, as a problem document";
			body = "[Problem](/docs/api/errors)";
		} else if (res.$ref === "#/components/responses/ValidationError") {
			meaning = "The input was refused; `errors` names each field";
			body = "[Problem](/docs/api/errors)";
		} else {
			const s = res.content?.["application/json"]?.schema;
			if (s) {
				const name = refName(s);
				body = name ? code(name) : code(typeOf(resolve(s)));
				if (/^2/.test(status)) {
					example = resolve(s).examples?.[0];
					exampleName = name;
				}
			} else if (/^2/.test(status)) body = "No body";
		}
		rows.push([status === "default" ? "Other" : status, esc(meaning), body]);
	}
	let out = table(["Status", "Meaning", "Body"], rows);
	if (exampleName === "ConversionView") {
		out += `\n\nA \`ConversionView\` is described under [the conversion object](/docs/api/conversions#the-conversion-object). Poll it, or follow its [event stream](/docs/api/conversions#get-apiv1conversionsidevents).`;
	} else if (example !== undefined) {
		const text = json(example);
		if (text.split("\n").length <= 40) out += `\n\nExample of a success body:\n\n\`\`\`json\n${text}\n\`\`\``;
	}
	return out;
}

function routeSection(r: Route): string {
	const heading = `${r.method} ${r.path}`;
	const out: string[] = [`## ${escapeBraces(heading)}`, ""];
	if (r.op.summary) out.push(`**${esc(cap(r.op.summary))}.**`, "");
	if (r.op.description) out.push(esc(r.op.description), "");
	out.push(table(["Property", "Value"], [["Auth", r.op.security ? "API key (`Authorization: Bearer` or `X-API-Key`)" : "None"], ["Ability", abilityOf(r)]]), "");
	const params = r.op.parameters ?? [];
	if (params.length) {
		out.push("**Parameters**", "");
		out.push(
			table(
				["Name", "In", "Type", "Required", "Notes"],
				params.map((p) => {
					const s = resolve(p.schema);
					return [code(p.name), p.in, esc(typeOf(s)), p.required ? "yes" : "no", esc([p.description ? cap(p.description) : "", constraints(s)].filter(Boolean).join(" "))];
				}),
			),
			"",
		);
	}
	const bodySchema = r.op.requestBody?.content?.["application/json"]?.schema;
	if (bodySchema) {
		const rows = fields(bodySchema);
		out.push("**Request body** (`application/json`)", "", fieldTable(rows), "");
	}
	out.push("**Example**", "", "```bash", curlFor(r), "```", "", "**Responses**", "", responseSection(r), "");
	return out.join("\n");
}


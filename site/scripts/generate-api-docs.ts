function operationPage(r: Route): string {
	const main: string[] = [];
	main.push("## Authentication", authText(r));

	const params = r.op.parameters ?? [];
	for (const [place, heading] of [
		["path", "Path parameters"],
		["query", "Query parameters"],
		["header", "Header parameters"],
	] as const) {
		const list = params.filter((p) => p.in === place);
		if (!list.length) continue;
		main.push(
			`## ${heading}`,
			table(
				["Name", "Type", "Required", "Description"],
				list.map((p) => [code(p.name), typeCell(p.schema), p.required ? "yes" : "no", describe(p.schema, p.description)]),
			),
		);
	}

	const bodySchema = r.op.requestBody?.content?.["application/json"]?.schema;
	if (bodySchema) {
		main.push("## Request body", `Content type ${code("application/json")}${r.op.requestBody?.required ? "." : ", optional."}`);
		main.push(hasProperties(bodySchema) ? propertyTable(bodySchema) : "The body has no members.");
	}

	main.push("## Responses");
	const exampleBlocks: string[] = [];
	if (r.slug === "conversions.events") {
		main.push(
			"### 200 OK",
			`Content type ${code("text/event-stream")}. The first event is always the current state, so a client that connects after the work is done still learns the outcome. Then come the events it missed after \`Last-Event-ID\`, then live ones. When the conversion has ended the server closes the stream. A conversion that is not yours is a \`404\`.`,
			"Every event is named `progress`. Its `data` is one JSON object:",
			table(["Name", "Type", "Required", "Description"], EVENT_FIELDS),
			"### 401 Unauthorized",
			`Content type ${code("application/problem+json")}. Schema: ${schemaLink("Problem")}.`,
			"### 404 Not Found",
			`Content type ${code("application/problem+json")}. No such conversion, or it is not yours. Schema: ${schemaLink("Problem")}.`,
		);
		exampleBlocks.push(
			fence(
				"text",
				`event: progress\ndata: {"id":0,"conversion_id":"01JQ8Z5X0K7M3N9P2R4T6V8W0Y","status":"running","progress":0,"phase":"","message":"","at":"2026-01-02T15:04:05Z"}`,
				"200",
			),
		);
	} else {
		for (const [status, raw] of Object.entries(r.op.responses ?? {})) {
			const res = resolveResponse(raw);
			const label = status === "default" ? "Any other status" : `${status}${STATUS_TEXT[status] ? ` ${STATUS_TEXT[status]}` : ""}`;
			main.push(`### ${label}`);
			const media = res.content ? Object.entries(res.content)[0] : undefined;
			const said = res.description && res.description !== STATUS_TEXT[status] ? `${esc(cap(res.description))}. ` : "";
			if (!media) {
				main.push(said.trim() || "No body.");
				continue;
			}
			const [type, body] = media;
			const name = refName(body.schema);
			main.push(`Content type ${code(type)}. ${said}${name ? `Schema: ${schemaLink(name)}.` : ""}`.trim());
			if (/^2/.test(status) && hasProperties(body.schema)) main.push(propertyTable(body.schema));
			if (!/^2/.test(status) && type === "application/problem+json") {
				main.push("The error follows RFC 9457. See [Errors](/docs/api/overview#errors).");
			}
			if (status !== "default") exampleBlocks.push(fence("json", json(exampleOf(body.schema)), status));
		}
	}

	const aside: string[] = ["<CodeGroup>", ...samples(sampleRequest(r)).map((s) => fence(s.lang, s.code, s.label)), "</CodeGroup>"];
	if (exampleBlocks.length) {
		aside.push(
			"**Response examples**",
			"<CodeGroup>",
			...exampleBlocks,
			"</CodeGroup>",
			"The examples are built from the schemas, so every value is a placeholder of its type. The tables above hold the fields that carry the real values.",
		);
	}

	const summary = cap(r.op.summary ?? r.op.operationId);
	const lead = r.op.description ? r.op.description.replace(/\s*\n+\s*/g, " ") : `${r.method} ${r.path}`;
	return page(
		summary,
		lead,
		[
			`<ApiRoute method="${r.method}" path="${r.path}" />`,
			"<RefSplit>",
			"<RefMain>",
			main.join("\n\n"),
			"</RefMain>",
			"<RefAside>",
			aside.join("\n\n"),
			"</RefAside>",
			"</RefSplit>",
		].join("\n\n"),
		{ badge: r.method, wide: true },
	);
}

function endpointsPage(): string {
	const sections = GROUPS.map((g) => {
		const list = routes.filter((r) => r.group === g.title);
		if (!list.length) return "";
		return [
			`## ${g.title}`,
			table(
				["Method", "Path", "Operation"],
				list.map((r) => [code(r.method), code(r.path).replace(/[{}]/g, (c) => `\\${c}`), `[${esc(cap(r.op.summary ?? r.slug))}](/docs/api/${r.slug})`]),
			),
		].join("\n\n");
	}).filter(Boolean);
	return page(
		"Endpoints",
		`All ${routes.length} routes under /api/v1, grouped by resource.`,
		[
			`The API has ${routes.length} routes under \`/api/v1\`. Each has its own page with the parameters, the body, the responses and a request in eight languages. The page of an operation is at \`/docs/api/<resource>.<action>\`.`,
			"Two more routes sit outside `/api/v1` because they do not speak JSON: the resumable upload at `/uploads/tus/` and the signed download of a result. Both are in [the quick start](/docs/api/overview#quick-start).",
			...sections,
		].join("\n\n"),
	);
}

function schemasPage(): string {
	const names = Object.keys(doc.components.schemas).sort((a, b) => a.localeCompare(b));
	const sections = names.map((name) => {
		const s = doc.components.schemas[name] as Schema;
		const r = resolve(s);
		const body = hasProperties(s) ? propertyTable(s) : `A value of type ${typeCell({ ...s, $ref: undefined })}${constraints(r) ? `: ${esc(constraints(r))}` : ""}.`;
		return [`## ${name}`, r.description ? esc(cap(r.description)) : "", body].filter(Boolean).join("\n\n");
	});
	return page(
		"Schemas",
		`The ${names.length} objects the HTTP API takes and returns, from its OpenAPI document.`,
		["The types named in the tables of the operations. Each links here by its name.", ...sections].join("\n\n"),
	);
}

function apiPages(): Map<string, string> {
	const pages = new Map<string, string>();
	for (const r of routes) pages.set(`api/${r.slug}`, operationPage(r));
	pages.set("api/endpoints", endpointsPage());
	pages.set("api/schemas", schemasPage());
	return pages;
}


type Route = { method: string; path: string; op: Operation; slug: string; group: string };

const METHOD_RANK: Record<string, string> = { GET: "0", POST: "1", PUT: "2", PATCH: "3", DELETE: "4" };

/** `<resource>.<action>`: the operation id when it has a dot, else the id as the resource of its only action. */
function slugOf(op: Operation): string {
	if (op.operationId.includes(".")) return op.operationId;
	return op.operationId === "abilities" ? "abilities.index" : `${op.operationId}.show`;
}


/** Escapes text for an MDX body: braces and angle brackets are syntax, a pipe ends a table cell. */
function esc(text: string): string {
	return text
		.replace(/\r?\n+/g, " ")
		.replace(/[\\{}<>|]/g, (c) => ({ "\\": "\\\\", "{": "\\{", "}": "\\}", "<": "&lt;", ">": "&gt;", "|": "\\|" })[c] as string);
}
/** A heading is MDX, where a brace opens a JavaScript expression. The anchor is the same without them. */
const escapeBraces = (s: string): string => s.split("{").join("\\{").split("}").join("\\}");
const code = (s: string): string => `\`${s.replace(/\|/g, "\\|")}\``;
const cap = (s: string): string => s.charAt(0).toUpperCase() + s.slice(1);

function table(head: string[], rows: string[][]): string {
	const line = (c: string[]): string => `| ${c.join(" | ")} |`;
	return [line(head), line(head.map(() => "---")), ...rows.map(line)].join("\n");
}

function pageText(title: string, description: string, body: string): string {
	return `---\ntitle: ${JSON.stringify(title)}\ndescription: ${JSON.stringify(description)}\n---\n\n${GENERATED}\n\n${body.trim().split("https://tools.example.com").join("http://localhost:3000")}\n`;
}

function json(value: unknown): string {
	return JSON.stringify(value, null, 2);
}

// ---------------------------------------------------------------- schemas

function resolve(s: Schema | undefined): Schema {
	if (!s) return {};
	if (s.$ref) {
		const name = s.$ref.replace("#/components/schemas/", "");
		return { ...resolve(doc.components.schemas[name]), ...(s.description ? { description: s.description } : {}) };
	}
	if (s.allOf) {
		const merged: Schema = {};
		for (const part of s.allOf) Object.assign(merged, resolve(part));
		return { ...merged, ...(s.description ? { description: s.description } : {}) };
	}
	return s;
}

const refName = (s: Schema | undefined): string | undefined =>
	(s?.$ref ?? s?.allOf?.find((p) => p.$ref)?.$ref)?.replace("#/components/schemas/", "");

function typeOf(s: Schema): string {
	const t = Array.isArray(s.type) ? s.type.filter((x) => x !== "null").join(" or ") : (s.type ?? "object");
	const nullable = Array.isArray(s.type) && s.type.includes("null") ? " or null" : "";
	if (t === "array") return `array of ${s.items ? typeOf(resolve(s.items)) : "values"}${nullable}`;
	return `${t}${nullable}`;
}

function constraints(s: Schema): string {
	const out: string[] = [];
	if (s.enum) out.push(`one of ${s.enum.map((v) => code(String(v))).join(", ")}`);
	if (s.minimum !== undefined) out.push(`min ${s.minimum}`);
	if (s.maximum !== undefined) out.push(`max ${s.maximum}`);
	if (s.minLength !== undefined && s.minLength > 0) out.push(`min length ${s.minLength}`);
	if (s.maxLength !== undefined) out.push(`max length ${s.maxLength}`);
	if (s.minItems !== undefined && s.minItems > 0) out.push(`at least ${s.minItems} items`);
	if (s.maxItems !== undefined) out.push(`at most ${s.maxItems} items`);
	if (s.pattern) out.push(`pattern ${code(s.pattern)}`);
	if (s.default !== undefined) out.push(`default ${code(JSON.stringify(s.default))}`);
	return out.join("; ");
}

type Row = { path: string; type: string; required: boolean; text: string };

/** Flattens an object schema into rows with dotted paths, down to `depth` levels. */
function fields(schema: Schema | undefined, prefix = "", depth = 3): Row[] {
	const s = resolve(schema);
	const rows: Row[] = [];
	for (const [name, raw] of Object.entries(s.properties ?? {})) {
		const p = resolve(raw);
		const full = prefix + name;
		const note = [p.description ? cap(p.description.replace(/\s+/g, " ")) : "", constraints(p)].filter(Boolean).join(" ");
		rows.push({ path: full, type: typeOf(p), required: (s.required ?? []).includes(name), text: note });
		if (depth > 1 && p.properties) rows.push(...fields(p, `${full}.`, depth - 1));
		else if (depth > 1 && p.type === "array" && p.items && resolve(p.items).properties)
			rows.push(...fields(resolve(p.items), `${full}[].`, depth - 1));
	}
	return rows;
}

function fieldTable(rows: Row[]): string {
	return table(
		["Field", "Type", "Required", "Notes"],
		rows.map((r) => [code(r.path), esc(r.type), r.required ? "yes" : "no", esc(r.text)]),
	);
}


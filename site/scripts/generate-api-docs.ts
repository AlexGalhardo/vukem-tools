function placeholder(s: Schema): unknown {
	const p = resolve(s);
	if (p.default !== undefined && p.default !== "") return p.default;
	if (p.enum) return p.enum[0];
	if (p.type === "integer" || p.type === "number") return p.minimum && p.minimum > 0 ? p.minimum : 1;
	if (p.type === "boolean") return true;
	if (p.type === "array") return [];
	if (p.type === "object") return {};
	return "text";
}

/** The options of the matching API example when there is one, else placeholders for the required fields. */
function exampleOptions(t: Tool): Record<string, unknown> | undefined {
	if (!t.options_required) return undefined;
	const op = routes.find((r) => r.op.operationId === t.operation);
	const body = resolve(op?.op.requestBody?.content?.["application/json"]?.schema).examples?.[0] as { options?: Record<string, unknown> } | undefined;
	if (body?.options && Object.keys(body.options).length) return body.options;
	const out: Record<string, unknown> = {};
	for (const k of t.options?.required ?? []) out[k] = placeholder(t.options?.properties?.[k] ?? {});
	return out;
}


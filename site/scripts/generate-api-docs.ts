// ---------------------------------------------------------------- text helpers

/** Escapes text for an MDX body: braces and angle brackets are syntax, and a pipe ends a table cell. */
function esc(text: string): string {
	return text
		.replace(/\s*\n+\s*/g, " ")
		.replace(/[\\{}<>|]/g, (c) => ({ "\\": "\\\\", "{": "\\{", "}": "\\}", "<": "&lt;", ">": "&gt;", "|": "\\|" })[c] as string);
}
const code = (s: string): string => `\`${s.replace(/\\/g, "\\\\").replace(/\|/g, "\\|")}\``;
const cap = (s: string): string => s.charAt(0).toUpperCase() + s.slice(1);
const slug = (s: string): string => new GithubSlugger().slug(s);

function table(head: string[], rows: string[][]): string {
	const line = (c: string[]): string => `| ${c.join(" | ")} |`;
	return [line(head), line(head.map(() => "---")), ...rows.map(line)].join("\n");
}

/** A fenced block whose fence is longer than any run of backticks inside it. */
function fence(lang: string, text: string, title?: string): string {
	const longest = Math.max(2, ...[...text.matchAll(/`+/g)].map((m) => m[0].length));
	const ticks = "`".repeat(longest + 1);
	return `${ticks}${lang}${title ? ` title=${JSON.stringify(title)}` : ""}\n${text}\n${ticks}`;
}

type Extras = { badge?: string; wide?: boolean };

/** The examples of the OpenAPI document name a real site and a placeholder host: a docs page names neither. */
const neutral = (text: string): string =>
	text
		.replace(/https:\/\/www\.youtube\.com\/watch\?v=[\w-]+/g, "https://example.com/video")
		.replace(/https:\/\/i\.ytimg\.com[^"\s]*/g, "https://example.com/thumbnail.jpg")
		.split("https://tools.example.com")
		.join(BASE_URL);

function page(title: string, description: string, body: string, extras: Extras = {}): string {
	const extra = [extras.badge ? `badge: ${JSON.stringify(extras.badge)}\n` : "", extras.wide ? "wide: true\n" : ""].join("");
	return `---\ntitle: ${JSON.stringify(title)}\ndescription: ${JSON.stringify(description)}\n${extra}---\n\n${GENERATED}\n\n${neutral(body.trim())}\n`;
}

const json = (value: unknown): string => JSON.stringify(value, null, 2);

// ---------------------------------------------------------------- schemas

const refName = (s: Schema | undefined): string | undefined =>
	(s?.$ref ?? s?.allOf?.find((p) => p.$ref)?.$ref)?.replace("#/components/schemas/", "");

function resolve(s: Schema | undefined): Schema {
	if (!s) return {};
	if (s.$ref) {
		const name = s.$ref.replace("#/components/schemas/", "");
		return { ...resolve(doc.components.schemas[name]), ...(s.description ? { description: s.description } : {}) };
	}
	if (s.allOf) {
		const merged: Schema = {};
		for (const part of s.allOf) Object.assign(merged, resolve(part));
		return { ...merged, ...(s.description ? { description: s.description } : {}), ...(s.examples ? { examples: s.examples } : {}) };
	}
	return s;
}

const schemaLink = (name: string): string => `[${code(name)}](/docs/api/schemas#${slug(name)})`;

/** A schema as the text of a table cell, with a link to the schema page for a named object. */
function typeCell(s: Schema | undefined): string {
	if (!s) return "";
	const name = refName(s);
	if (name) return schemaLink(name);
	const types = Array.isArray(s.type) ? s.type : [s.type ?? "object"];
	const main = types.filter((t) => t !== "null");
	const nullable = types.includes("null") ? " or `null`" : "";
	if (main[0] === "array") return `array of ${s.items ? typeCell(s.items) : code("any")}${nullable}`;
	if (main[0] === "object" && typeof s.additionalProperties === "object" && !s.properties) {
		return `map of ${typeCell(s.additionalProperties)}${nullable}`;
	}
	return `${main.map((t) => code(t + (s.format ? ` (${s.format})` : ""))).join(" or ")}${nullable}`;
}

function constraints(s: Schema): string {
	const out: string[] = [];
	if (s.enum) out.push(`one of ${s.enum.map((v) => code(String(v))).join(", ")}`);
	if (s.minimum !== undefined) out.push(`min ${s.minimum}`);
	if (s.maximum !== undefined) out.push(`max ${s.maximum}`);
	if (s.minLength !== undefined && s.minLength > 0) out.push(`min length ${s.minLength}`);
	if (s.maxLength !== undefined) out.push(`max length ${s.maxLength}`);
	if (s.minItems !== undefined && s.minItems > 0) out.push(`at least ${s.minItems} items`);
	if (s.maxItems !== undefined) out.push(`at most ${s.maxItems} items`);
	if (s.pattern) out.push(`pattern ${code(s.pattern)}`);
	if (s.default !== undefined) out.push(`default ${code(JSON.stringify(s.default))}`);
	return out.join("; ");
}

/** The description of a property or parameter: its sentence, then its constraints. */
function describe(s: Schema | undefined, text?: string): string {
	const r = resolve(s);
	const sentence = text ?? r.description ?? "";
	const note = constraints(r);
	const said = sentence.trim().replace(/.$/, "");
	return [said ? esc(cap(said)) : "", note].filter(Boolean).join(said && note ? ". " : "");
}

function propertyTable(schema: Schema | undefined): string {
	const s = resolve(schema);
	const required = new Set(s.required ?? []);
	return table(
		["Name", "Type", "Required", "Description"],
		Object.entries(s.properties ?? {}).map(([name, p]) => [code(name), typeCell(p), required.has(name) ? "yes" : s.required ? "no" : "-", describe(p)]),
	);
}

const hasProperties = (schema: Schema | undefined): boolean => Object.keys(resolve(schema).properties ?? {}).length > 0;

/** A sample value of a schema: its first example, its default, its first enum value, else a placeholder of its type. */
function exampleOf(schema: Schema | undefined, depth = 0): unknown {
	if (!schema) return null;
	if (schema.examples?.length) return schema.examples[0];
	const s = resolve(schema);
	if (s.examples?.length) return s.examples[0];
	if (s.default !== undefined && s.default !== "") return s.default;
	if (s.enum) return s.enum[0];
	const type = (Array.isArray(s.type) ? s.type.find((t) => t !== "null") : s.type) ?? (s.properties ? "object" : "string");
	if (type === "object") {
		if (depth >= 3) return {};
		const required = new Set(s.required ?? []);
		return Object.fromEntries(
			Object.entries(s.properties ?? {})
				.filter(([k]) => required.has(k) || depth === 0)
				.map(([k, v]) => [k, exampleOf(v, depth + 1)]),
		);
	}
	if (type === "array") return depth >= 3 ? [] : [exampleOf(s.items, depth + 1)];
	if (type === "integer" || type === "number") return s.minimum && s.minimum > 0 ? s.minimum : 1;
	if (type === "boolean") return true;
	return s.format === "date-time" ? "2026-01-02T15:04:05Z" : "text";
}


// Generates the API reference and the MCP tool reference of the docs site.
//
// The pattern is the one of https://stuarty.com/docs/api/overview/: one page per API operation at
// /docs/api/<resource>.<action>/, one page per MCP tool at /docs/mcp/tools/<name>/, an endpoint index and a
// schema page. Nothing on a generated page is written by hand per route or per tool.
//
// Sources:
//   - site/generated/openapi.json: a snapshot of GET /openapi.json of the running app (the field `servers` is dropped).
//     Refresh it after any route change: `curl localhost:3000/openapi.json`. `openapi:export` is not a substitute:
//     without a path prefix it also describes the web pages.
//   - internal/toolkit/tools.json: the table the CLI and the MCP server read (54 tools).
//   - ABILITY below: the ability each tool route demands. It comes from the Ability() methods under app/tools; the
//     script refuses to run when a tool of tools.json has no entry here.
//
// Writes content/generated/api/*.mdx, content/generated/mcp/**/*.mdx and generated/api-nav.json (the sidebar groups,
// which content/navigation.ts reads). Run from site/:
//   node scripts/generate-api-docs.ts             write the pages and delete the ones that no longer have a source
//   node scripts/generate-api-docs.ts --check     fail when a file on disk differs from what would be written
//   node scripts/generate-api-docs.ts --coverage  also prove every route and every tool is documented
// Node strips the types; it needs no dependency besides github-slugger, which the site already has.

// Renders the glossary pages (TASK-0267) from content/glossary/*.json: one MDX page per topic and an A to Z page.
// Called by generate-reference.ts, so `npm run reference` writes them and `reference:check` fails on a drift.
import { allTerms, entries, resolveSource, sourceRegistry, termId, termPath, topics, type Located, type Topic } from "../lib/glossary-data.ts";

const GENERATED = "{/* Generated by site/scripts/generate-reference.ts from content/glossary. Do not edit. */}";

/** Escapes prose for MDX: braces and angle brackets are syntax outside inline code. */
export function escProse(text: string): string {
	return text
		.split(/(`[^`]*`)/)
		.map((part, i) => (i % 2 === 1 ? part : part.replace(/[{}<>]/g, (c) => ({ "{": "&#123;", "}": "&#125;", "<": "&lt;", ">": "&gt;" })[c] as string)))
		.join("");
}

function front(title: string, description: string): string {
	return `---\ntitle: ${JSON.stringify(title)}\ndescription: ${JSON.stringify(description)}\n---\n\n${GENERATED}\n`;
}

const letter = (term: string): string => term.charAt(0).toUpperCase();

function entryBlock(t: Located, byId: Map<string, Located>, registry: ReturnType<typeof sourceRegistry>): string {
	const out = [`### ${escProse(t.term)}`, "", escProse(t.meaning), "", `**Example.** ${escProse(t.example)}`];
	if (t.vukem) out.push("", `**In Vukem Tools.** ${escProse(t.vukem)}`);

	const bits: string[] = [];
	if (t.aka?.length) bits.push(`**Also called:** ${t.aka.map(escProse).join(", ")}.`);
	if (t.see?.length) {
		const links = t.see.map((s) => {
			const other = byId.get(termId(s));
			if (!other) throw new Error(`glossary: "${t.term}" says see "${s}", which is not a term`);
			const href = other.topic.slug === t.topic.slug ? `#${other.id}` : termPath(other);
			return `[${escProse(other.term)}](${href})`;
		});
		bits.push(`**See also:** ${links.join(", ")}.`);
	}
	if (bits.length) out.push("", bits.join(" "));

	if (t.sources?.length) {
		const links = t.sources.map((key) => {
			const s = resolveSource(key, registry);
			if (!s) throw new Error(`glossary: "${t.term}" cites "${key}", which is not a source`);
			return `[${escProse(s.title)}](${s.url})`;
		});
		out.push("", `**Learn more:** ${links.join(" · ")}`);
	}
	return out.join("\n");
}

export function topicPage(topic: Topic): string {
	const registry = sourceRegistry();
	const byId = new Map(allTerms().map((t) => [t.id, t]));
	const list = entries(topic.slug).map((e) => byId.get(termId(e.term)) as Located);
	const jump = `Terms on this page: ${list.length}. ${escProse(topic.intro)}`;
	return `${front(topic.title, topic.description)}\n${jump}\n\n${list.map((t) => entryBlock(t, byId, registry)).join("\n\n")}\n`;
}

/** Every term in one list, by first letter, each with its tip and a link to its entry. */
export function indexPage(): string {
	const all = [...allTerms()].sort((a, b) => a.term.localeCompare(b.term, "en", { sensitivity: "base" }));
	const byLetter = new Map<string, Located[]>();
	for (const t of all) byLetter.set(letter(t.term), [...(byLetter.get(letter(t.term)) ?? []), t]);
	const body = [...byLetter.entries()]
		.map(([l, items]) => `## ${/[A-Z]/.test(l) ? l : "Numbers and symbols"}\n\n${items.map((t) => `- [${escProse(t.term)}](${termPath(t)}): ${escProse(t.tip)}`).join("\n")}`)
		.join("\n\n");
	return `${front("Glossary A to Z", `Every term of the glossary in one list, with a short explanation and a link to the full entry. ${all.length} terms.`)}\nPick a letter, read the short explanation and follow the link for the example and the sources. The terms are also grouped by topic, in the pages of this section.\n\n${body}\n`;
}

export const topicPages = (): { file: string; text: string }[] => [
	...topics().map((t) => ({ file: `${t.slug}.mdx`, text: topicPage(t) })),
	{ file: "a-to-z.mdx", text: indexPage() },
];

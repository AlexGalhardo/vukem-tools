// Small helpers shared by the generators of the reference pages (generate-reference.ts and the API and MCP
// modules). Node strips the types.
export const GENERATED = "{/* Generated by site/scripts/generate-reference.ts. Do not edit. */}";

/** Escapes text for an MDX body: backslash is an escape char, braces/angle brackets are syntax, and a pipe ends a table cell. */
export function esc(text: string): string {
	return text.replace(/[\\{}<>|]/g, (c) => ({ "\\": "\\\\", "{": "\\{", "}": "\\}", "<": "&lt;", ">": "&gt;", "|": "\\|" })[c] as string);
}

/** A line that starts with "import" or "export" is ESM to MDX, so a summary starts with a capital. */
export const sentence = (text: string): string => text.charAt(0).toUpperCase() + text.slice(1);

export const code = (text: string): string => `\`${text.replace(/\\/g, "\\\\").replace(/\|/g, "\\|")}\``;

/** Extra front matter keys a page may carry: `badge` (the sidebar label of an API method) and `wide` (no table of contents, two columns). */
export type PageExtras = { badge?: string; wide?: boolean };

export function page(title: string, description: string, body: string, extras: PageExtras = {}): string {
	const extra = [extras.badge ? `badge: ${JSON.stringify(extras.badge)}\n` : "", extras.wide ? "wide: true\n" : ""].join("");
	return `---\ntitle: ${JSON.stringify(title)}\ndescription: ${JSON.stringify(description)}\n${extra}---\n\n${GENERATED}\n\n${body.trim()}\n`;
}

export function table(head: string[], rows: string[][]): string {
	const line = (cells: string[]) => `| ${cells.join(" | ")} |`;
	return [line(head), line(head.map(() => "---")), ...rows.map(line)].join("\n");
}

/** A fenced block whose fence is longer than any run of backticks inside, so a sample can never close it early. */
export function fence(lang: string, text: string, title?: string): string {
	const longest = Math.max(2, ...[...text.matchAll(/`+/g)].map((m) => m[0].length));
	const ticks = "`".repeat(longest + 1);
	return `${ticks}${lang}${title ? ` title=${JSON.stringify(title)}` : ""}\n${text}\n${ticks}`;
}
